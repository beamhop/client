#!/usr/bin/env -S npx tsx
/**
 * Generate docs/cli.md — the full `beamhop` command reference — from commander's own help output,
 * so the reference can never drift from the code.
 *
 *   pnpm exec tsx scripts/gen-cli-docs.ts           write docs/cli.md
 *   pnpm exec tsx scripts/gen-cli-docs.ts --check   exit 1 if docs/cli.md is stale
 *
 * The program is built with a client that throws: help rendering never calls the daemon.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildProgram, type CliIO } from '../apps/cli/src/program.ts';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'docs', 'cli.md');
const WIDTH = 100;

const io: CliIO = {
  out: () => {},
  err: () => {},
  readStdin: async () => '',
  env: {},
};
const program = buildProgram({
  io,
  client: async () => {
    throw new Error('not connected (docs generation)');
  },
});

type Cmd = ReturnType<typeof buildProgram>;

const fullName = (c: Cmd): string => {
  const parts: string[] = [];
  for (let x: Cmd | null = c; x; x = x.parent as Cmd | null) parts.unshift(x.name());
  return parts.join(' ');
};

const anchor = (s: string): string =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9 -]/g, '')
    .trim()
    .replace(/\s+/g, '-');

const sections: string[] = [];
const index: string[] = [];
const walk = (c: Cmd, depth: number): void => {
  c.configureHelp({ helpWidth: WIDTH, sortSubcommands: false });
  const name = fullName(c);
  const help = c.helpInformation().trimEnd();
  if (depth > 0) {
    index.push(`${'  '.repeat(depth - 1)}- [\`${name}\`](#${anchor(name)})`);
    sections.push(`${'#'.repeat(Math.min(depth + 1, 4))} ${name}\n\n\`\`\`text\n${help}\n\`\`\`\n`);
  }
  for (const sub of c.commands as Cmd[]) {
    if ((sub as unknown as { _hidden?: boolean })._hidden) continue;
    walk(sub, depth + 1);
  }
};
program.configureHelp({ helpWidth: WIDTH });
const rootHelp = program.helpInformation().trimEnd();
walk(program, 0);

const doc = `# CLI reference

<!-- Generated by scripts/gen-cli-docs.ts from commander's help output. Do not edit by hand:
     run \`pnpm exec tsx scripts/gen-cli-docs.ts\` after changing apps/cli/src/program.ts. -->

Every command talks to the local daemon (\`beamhop daemon\`) over its localhost API, using the token in
\`$BEAMHOP_HOME/api-token\`. Add \`--json\` before the command for machine-readable output, for example
\`beamhop --json agent ls\`. Environment: \`BEAMHOP_HOME\` (default \`~/.beamhop\`), \`BEAMHOP_PORT\`
(default 7878), \`BEAMHOP_URL\` and \`BEAMHOP_TOKEN\` to target another daemon.

\`\`\`text
${rootHelp}
\`\`\`

## Commands

${index.join('\n')}

${sections.join('\n')}`;

if (process.argv.includes('--check')) {
  let cur = '';
  try {
    cur = readFileSync(OUT, 'utf8');
  } catch {
    // missing counts as stale
  }
  if (cur !== doc) {
    console.error('docs/cli.md is stale: run `pnpm exec tsx scripts/gen-cli-docs.ts`');
    process.exit(1);
  }
  console.log('docs/cli.md is up to date');
} else {
  writeFileSync(OUT, doc);
  console.log(`wrote ${OUT} (${sections.length} commands)`);
}
